import test from 'node:test';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const T=require('../prototypes/f8-jaeger/f8-trainer.js');
const FLUG=require('../prototypes/flug2d/flug-kern.js');
const cmd=(type,fields={})=>({type,owner:'house',schiff:T.ID,...fields});
const pruefe=s=>assert.equal(T.audit(s).ok,true,T.audit(s).grund);
test('F8: Original-F6-Flugkern verwendet echte Jaegerflugwerte, aber kein wirtschaftlich erzeugtes Schiff',()=>{
  const s=T.neu();pruefe(s);
  assert.equal(s.schema,0);
  assert.equal(s.profil,'F8_FLUGUEBUNG_OHNE_WIRTSCHAFT');
  assert.equal(s.ships[T.ID].klasse,'jaeger');
  assert.equal(FLUG.DATEN.klassen.jaeger.vmax,4160);
  assert.equal(FLUG.DATEN.klassen.jaeger.drehrate,10);
  for(const f of ['owners','ledger','geld','minted','burned','kampf','kopfgeld','xp','rulesVersion'])
    assert.equal(Object.hasOwn(s,f),false,f+' darf kein Wirtschaftsbetrag sein');
  assert.match(T.begrenzung,/kein wirtschaftlich/);
  const old=JSON.stringify(s);
  assert.equal(T.befehl(s,cmd('shipMine',{ware:'erz'})).ok,false);
  assert.equal(T.befehl(s,cmd('shipSteer',{kurs:5,fahrt:40})).ok,false,'erst abdocken');
  assert.equal(T.befehl(s,{type:'shipUndock',owner:'pirates',schiff:T.ID}).ok,false);
  assert.equal(JSON.stringify(s),old);
  assert.throws(()=>T.schritt(s,0),/1\.\.12000/);
  assert.throws(()=>T.schritt(s,12001),/1\.\.12000/);
  assert.equal(JSON.stringify(s),old);
});
test('F8: bezahlungsfreie Fluguebung nutzt exakt denselben F6-Integerintegrator mit Jägerbewegung',()=>{
  const s=T.neu();
  assert.equal(T.befehl(s,cmd('shipUndock')).ok,true);
  T.schritt(s,39);assert.equal(T.status(s).lage,'abdocken');
  T.schritt(s,1);assert.equal(T.status(s).lage,'frei');
  assert.equal(T.befehl(s,cmd('shipSteer',{kurs:64,fahrt:90})).ok,true);
  T.schritt(s,45);pruefe(s);
  assert.notEqual(T.status(s).y,0);
  assert.ok(T.status(s).sekunden>=85);
  const s2=T.neu();T.befehl(s2,cmd('shipUndock'));T.schritt(s2,40);
  T.befehl(s2,cmd('shipSteer',{kurs:64,fahrt:90}));T.schritt(s2,45);
  assert.deepEqual(s2,s,'identische Kommandos und Schritte = identischer Zustand');
  const clone=JSON.parse(JSON.stringify(s));pruefe(clone);
  assert.deepEqual(clone,s);
  clone.ships[T.ID].owner='pirates';assert.equal(T.audit(clone).ok,false,'kein fremdes Schiff');
  clone.ships[T.ID].owner='house';clone.minted=900;
  assert.equal(T.audit(clone).ok,false,'keine versteckte Gutschrift');
});
test('F8: realer 2D-Zielanflug und Bremse, anschließend Dock via Original-Flugkern',()=>{
  const s=T.neu();
  T.befehl(s,cmd('shipUndock'));T.schritt(s,40);
  assert.equal(T.befehl(s,cmd('shipFlyTo',{x:T.MARKER.x,y:T.MARKER.y})).ok,true);
  for(let i=0;i<6000&&s.erreicht===null;i++)T.schritt(s);
  assert.equal(s.erreicht,265,'exakter deterministischer Integerflug-Referenztick');
  assert.equal(T.status(s).bremsbereit,true,'kein schneller Vorbeiflug als Erfolg');
  assert.equal(T.befehl(s,cmd('shipDock',{station:'st_nadir'})).ok,false,'kein falscher Dock');
  assert.equal(T.befehl(s,cmd('shipDock',{station:'st_aldera'})).ok,true);
  for(let i=0;i<6000&&T.status(s).lage!=='angedockt';i++)T.schritt(s);
  assert.equal(T.status(s).lage,'angedockt');
  assert.equal(T.status(s).x,0);assert.equal(T.status(s).y,0);
  assert.equal(s.erreicht,265);
  pruefe(s);
  const replay=T.neu();T.befehl(replay,cmd('shipUndock'));T.schritt(replay,40);
  T.befehl(replay,cmd('shipFlyTo',{x:T.MARKER.x,y:T.MARKER.y}));
  T.schritt(replay,225);
  T.befehl(replay,cmd('shipDock',{station:'st_aldera'}));
  T.schritt(replay,s.sekunden-265);
  assert.deepEqual(replay,s,'vollständiger Trainingsflug bitgleich replaybar');
});
