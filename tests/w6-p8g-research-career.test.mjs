// W6/P8g: opt-in research career uses real Rule207 without Rule204 save migration.
import test from 'node:test';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const J8=require('../prototypes/verbund/konzern-session.js');
const W=require('../prototypes/welt/welt-kern.js');
const J13=require('../prototypes/spiel/jaeger-akte.js');
const J13b=require('../prototypes/spiel/jaeger-projekt.js');
const P8a=require('../prototypes/spiel/silizium-versorgung.js');
const sum=s=>Object.values(s.owners).reduce((n,o)=>n+o.cash,0);
function verify(j){
  const w=j.weltReferenz(),s=j.zustandReferenz(),json=j.exportieren();
  assert.equal(w.audit(s).ok,true,w.audit(s).fehler?.join('; '));
  assert.equal(w.hash(w.load(json)),w.hash(s));
  assert.equal(sum(s),33000);
  assert.equal(s.minted,0);assert.equal(s.burned,0);
  return {w,s,json};
}
test('W6/P8g: research career requires independent explicit opt-in and never edits Rule204',()=>{
  const career=J8.erstellen();
  assert.throws(()=>career.startenP8g(),/ausdrücklich/);
  const a=career.startenP8g(true);
  assert.equal(a.regel,207);assert.equal(a.weltgeld,33000);
  assert.equal(a.hausgeld,3000);
  const {w,s,json}=verify(career);
  assert.equal(s.kanon.materialSupplyEnabled,true);
  assert.equal(s.kanon.npcAuto,true);
  assert.equal(s.kanon.npcSilizium.aktiv,true);
  assert.equal(s.kanon.politik.stilllegung,true);
  assert.equal(w.p8gMaterialOnlyW3,true);
  assert.throws(()=>career.startenP8g(true),/laufende Sitzung/);
  assert.equal(J13.erstellen(w,s,career.angebote().find(x=>x.id==='buy-st_nadir-jaeger')).regel,207);
  assert.equal(J13b.erstellen(career).gruppen.length>0,true);
  const supply=P8a.erstellen(w,s);
  assert.equal(supply.regel,207);
  assert.equal(supply.rohstoff.rest,16,'endlicher Nadir-Lokalrest ohne Dravos-Auffuellung');
  assert.equal(supply.weg.dravosAktiv,true);
  const newSession=J8.erstellen();
  assert.throws(()=>newSession.oeffnenP8g(json,false),/Einwilligung/);
  assert.throws(()=>newSession.oeffnen204(json,true),/Nur Original-Regel204/);
  const restored=newSession.oeffnenP8g(json,true);
  assert.equal(restored.regel,207);
  assert.equal(newSession.exportieren(),json);
  verify(newSession);
  assert.deepEqual(newSession.ansicht().schiffe,career.ansicht().schiffe);
  const old=W.erstellenJ4c({carrierCash:2000,buyerCash:4000});
  const legacy=old.createState(42);
  const base=old.save(legacy),hash=old.hash(legacy);
  assert.equal(legacy.rulesVersion,204);
  assert.equal(old.hash(old.load(base)),hash);
  assert.equal(old.save(legacy),base);
  assert.equal(legacy.kanon.materialSupplyEnabled,undefined);
});
test('W6/P8g: real player buys own original miner; cockpit rights and save/load remain',()=>{
  const session=J8.erstellen();
  session.startenP8g(true);
  const before=verify(session);
  assert.ok(session.angebote().some(x=>x.id==='buy-st_aldera-miner'&&x.ok));
  const purchase=session.ausfuehren('buy-st_aldera-miner');
  assert.equal(purchase.ok,true,purchase.reason);
  const {w,s,json}=verify(session);
  assert.equal(s.owners.house.cash,2400,'echter 600-ISK-Kauf');
  const miner=Object.values(s.ships).find(x=>x.owner==='house'&&x.klasse==='miner');
  assert.ok(miner);assert.equal(miner.system,'aldera');
  const pilot=session.uebernehmen(miner.id,false);
  assert.equal(pilot.ok,true,pilot.reason);
  assert.equal(session.pilotStatus(),miner.id);
  const fly=session.flugBefehl({type:'shipUndock',owner:'house',schiff:miner.id});
  assert.equal(fly.ok,true,fly.reason);
  verify(session);
  const renewed=J8.erstellen();
  assert.equal(renewed.oeffnenP8g(session.exportieren(),true).regel,207);
  assert.equal(renewed.weltReferenz().hash(renewed.zustandReferenz()),session.weltReferenz().hash(session.zustandReferenz()));
  const old=J8.erstellen();
  assert.throws(()=>old.oeffnen204(json,true));
  assert.equal(before.s.rulesVersion,207);
});
