 assert.equal(b.werftFrachtBeitragVorWertverzehr,after.werftFrachtBeitragVorWertverzehr);
 assert.equal(b.werftFrachtBereit,after.werftFrachtBereit);
 assert.equal(j.zustandReferenz().minted,0);assert.equal(j.zustandReferenz().burned,0);
